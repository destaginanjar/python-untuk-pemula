
# Contoh penggunaan function

def salam(nama):
    print("Halo,", nama)
    print("Selamat belajar Python!")

def tambah(angka1, angka2):
    hasil = angka1 + angka2
    return hasil

# Memanggil function
salam("Aiman")

hasil_penjumlahan = tambah(10, 5)
print("Hasil penjumlahan:", hasil_penjumlahan)
