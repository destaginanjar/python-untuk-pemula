# Bab 2: Operator pada Python

# Operator Aritmatika
a = 10
b = 3

print("=== Operator Aritmatika ===")
print("Penjumlahan:", a + b)
print("Pengurangan:", a - b)
print("Perkalian:", a * b)
print("Pembagian:", a / b)
print("Pembagian Bulat:", a // b)
print("Modulus:", a % b)
print("Pangkat:", a ** b)

# Operator Perbandingan
print("\n=== Operator Perbandingan ===")
print("Sama dengan:", a == b)
print("Tidak sama dengan:", a != b)
print("Lebih besar:", a > b)
print("Lebih kecil:", a < b)

# Operator Logika
print("\n=== Operator Logika ===")
x = True
y = False

print("AND:", x and y)
print("OR:", x or y)
print("NOT:", not x)

# Operator Penugasan
print("\n=== Operator Penugasan ===")
angka = 10
angka += 5
print("Setelah += 5:", angka)

angka -= 3
print("Setelah -= 3:", angka)